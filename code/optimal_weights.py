r"""
Task 1 (Part III notes, Section 6): can an optimised weight function g close the 0.030 gap to (7,4) at theta = 1/2?

Weighted two-dimensional sieve (Part II, Section 7.2) with a general weight g >= 0 on [a, b), g = 0 on [b, 1]:
    W = sum_{n in A, (n(N-n), P(z)) = 1} w(n) (1 - lam sum_{p | n(N-n)} g(t_p)),   p = N^{t_p},  z = N^a,
    W >= X V(z) (f_2(theta/a) - lam R(g) - o(1)),   R(g) = 2 int_a^b g(t) F_2((theta - t)/a) dt/t.
An integer with positive weight has sum_{p | n(N-n)} g(t_p) < 1/lam.  With
    G_k(S) = inf { sum_{i=1}^k g(t_i) : t_i >= a, t_1 + ... + t_k <= S }      (g = 0 on [b,1], so large primes cost 0),
which is non-decreasing in k and non-increasing in S, the pair (k, k') follows from
    G_{k'+1}(1) >= 1/lam   (side)   and   2 G_{(k+1)/2}(1) >= 1/lam (joint, k odd; for k = 7: G_4(1) >= 1/(2 lam)).
Normalising lam = 1 the best margin for (k, k') at given (a, b) is
    f_2(theta/a) - min { R(g) : G_{k'+1}(1) >= 1, G_{(k+1)/2}(1) >= 1/2, g >= 0 },
a linear programme in the values of g on a grid, whose constraints (one per prime configuration) are generated by
cutting planes: the minimising configurations of the dynamic programme for G_k are added until none is violated.
For the linear weight g(t) = 1 - t/b one has G_k(1) = k - 1/b (whenever feasible) and the thresholds of Part II.
The script prints the optimal margins for (7,5), (7,4), (6,4) over a scan of (a, b), the optimal g, and also checks
scheme (ii): min over s_A + s_B = s of F_1(s_A) F_1(s_B) against F_2(s).  Floating point.
Usage: python optimal_weights.py [theta]
"""
import os
import sys
import numpy as np
from scipy.optimize import linprog

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'two-squares-mean-square', 'code'))
from dhr_sieve import DHR          # noqa: E402
from sieve_core import F_lin       # noqa: E402

theta = float(eval(sys.argv[1])) if len(sys.argv) > 1 else 0.5
D2 = DHR(2, verbose=False)
DELTA = 0.0025


class Weights:
    def __init__(self, a, b):
        self.ia = int(round(a / DELTA))
        assert abs(self.ia * DELTA - a) < 1e-12, "a must be a multiple of the grid step"
        self.a, self.b = a, b
        self.t = np.round(np.arange(a, 1.0 + DELTA / 2, DELTA), 10)       # grid of t = log p / log N: t[l] = a + l DELTA
        self.nvar = int(np.sum(self.t < b - 1e-12))                       # g is free on [a, b)
        self.cost = 2 * D2.Fs((theta - self.t[:self.nvar]) / a) * DELTA / self.t[:self.nvar]
        self.cost[0] *= 0.5                                               # trapezoid rule (g = 0 at and beyond b)

    def full(self, g):
        G = np.zeros(len(self.t))
        G[:self.nvar] = g
        return G

    def Gk(self, g, k, S=1.0):
        """G_j(S) for j <= k by dynamic programming on the grid (budgets S_i = i DELTA, primes t_l = a + l DELTA);
        returns the value G_k(S) and a minimising configuration."""
        G = self.full(g)
        n = len(self.t)
        ia = self.ia
        nb = int(round(S / DELTA)) + 1
        INF = 1e18
        V = np.full((k + 1, nb), INF)
        arg = np.zeros((k + 1, nb), dtype=np.int64)
        # j = 1: G_1(S_i) = min_{0 <= l <= i - ia} g[l]
        run = np.minimum.accumulate(G)
        runarg = np.zeros(n, dtype=np.int64)
        best = 0
        for l in range(n):
            if G[l] < G[best]:
                best = l
            runarg[l] = best
        for i in range(ia, nb):
            lmax = min(i - ia, n - 1)
            V[1][i] = run[lmax]
            arg[1][i] = runarg[lmax]
        for j in range(2, k + 1):
            for i in range(j * ia, nb):
                lmax = min(i - j * ia, n - 1)          # t_j = t[l] needs remaining budget (i - ia - l) DELTA >= (j-1) a
                cand = G[:lmax + 1] + V[j - 1][i - ia - np.arange(lmax + 1)]
                l = int(np.argmin(cand))
                V[j][i] = cand[l]
                arg[j][i] = l
        conf = []
        j, i = k, nb - 1
        while j >= 1:
            l = int(arg[j][i])
            conf.append(float(self.t[l]))
            i = i - ia - l
            j -= 1
        return float(V[k][nb - 1]), conf

    def row_of(self, conf):
        row = np.zeros(self.nvar)
        for tt in conf:
            idx = int(round((tt - self.a) / DELTA))
            if idx < self.nvar:
                row[idx] += 1
        return row

    def optimise(self, k, kp, tol=1e-7, maxit=600):
        """min R(g) subject to: G_{kp+1}(1) >= 1 (side) and G_{k1}(1) + G_{k2}(1) >= 1 for all k1 + k2 = k + 1 with
        k1, k2 <= kp (joint), by cutting planes; the bad configurations are those with Omega(n) > kp, Omega(N-n) > kp
        or Omega(n(N-n)) > k, and G_j is non-decreasing in j."""
        pairs = [(k1, k + 1 - k1) for k1 in range(1, k + 1) if k1 <= kp and k + 1 - k1 <= kp and k1 <= k + 1 - k1]
        rows, rhs, seen = [], [], set()
        g = np.zeros(self.nvar)
        for it in range(maxit):
            if rows:
                res = linprog(self.cost, A_ub=-np.array(rows), b_ub=-np.array(rhs), bounds=[(0, 5)] * self.nvar,
                              method="highs")
                if res.status != 0:
                    raise RuntimeError(res.message)
                g = res.x
            violated = False
            cache = {}
            for j in {kp + 1} | {k1 for k1, k2 in pairs} | {k2 for k1, k2 in pairs}:
                cache[j] = self.Gk(g, j)
            tests = [((kp + 1,), cache[kp + 1][0], self.row_of(cache[kp + 1][1]))]
            for k1, k2 in pairs:
                tests.append(((k1, k2), cache[k1][0] + cache[k2][0], self.row_of(cache[k1][1]) + self.row_of(cache[k2][1])))
            for lab, val, row in tests:
                if val < 1.0 - tol:
                    violated = True
                    nz = tuple(np.nonzero(row)[0])
                    key = (lab, nz, tuple(row[list(nz)]))
                    if key in seen:
                        raise RuntimeError(f"cycling on {lab} (value {val:.6f})")
                    seen.add(key)
                    rows.append(row)
                    rhs.append(1.0)
            if not violated:
                return g, float(self.cost @ g), it
        raise RuntimeError("no convergence")


def linear_margin(a, b, k, kp):
    """margin for the linear weight 1 - t/b with the best lam: L - lam R, 1/lam = min(k + 1 - 2/b, kp + 1 - 1/b)."""
    L = float(D2.fs(theta / a))
    t = np.linspace(a, b, 2001)
    R = 2 * float(np.trapz((1 - t / b) * D2.Fs((theta - t) / a) / t, t))
    inv = min(k + 1 - 2 / b, kp + 1 - 1 / b)
    if inv <= 0:
        return -9.0, L, R
    return L - R / inv, L, R


def best_linear(a, k, kp):
    best = None
    for b in np.arange(0.20, theta - 0.004, 0.0025):
        m, L, R = linear_margin(a, b, k, kp)
        if best is None or m > best[0]:
            best = (m, b, L, R)
    return best


if __name__ == "__main__":
    out = [f"theta = {theta}, grid step {DELTA}; margins f_2(theta/a) - R(g) with G_{{k'+1}}(1) >= 1 and G_k1(1) + G_k2(1) >= 1 "
           f"for k1 + k2 = k + 1, k1, k2 <= k' (lam = 1)"]
    # scheme (ii): F_2(s) against the best split of the vector sieve upper bound
    s = np.linspace(1.0, 10.0, 91)
    worst = 0.0
    for sv in s:
        sa = np.linspace(0.3, sv - 0.3, 200)
        vec = np.min(F_lin(sa) * F_lin(sv - sa))
        worst = max(worst, float(D2.Fs(sv)) / vec)
    out.append(f"scheme (ii): max over s in [1,10] of F_2(s) / min_(s_A+s_B=s) F_1(s_A)F_1(s_B) = {worst:.3f} "
               f"(< 1: the vector-sieve upper bound never beats F_2)")
    for (k, kp) in ((7, 5), (7, 4), (6, 4)):
        out.append(f"\npair ({k},{kp}): constraints G_{kp + 1}(1) >= 1 and G_k1(1) + G_k2(1) >= 1 for k1 + k2 = {k + 1}, k1, k2 <= {kp}; "
                   f"g free on [a, 0.49), the LP chooses its support")
        best = None
        b = 0.49
        for a in np.arange(0.045, 0.0751, 0.0025):
            lin, blin, L, R = best_linear(a, k, kp)
            Wt = Weights(a, b)
            try:
                g, Ropt, its = Wt.optimise(k, kp)
            except RuntimeError as exc:
                out.append(f"   a = {a:.4f}: LP failed ({exc})")
                continue
            marg = L - Ropt
            supp = Wt.t[:Wt.nvar][g > 1e-9].max() if np.any(g > 1e-9) else 0.0
            line = (f"   a = {a:.4f}: best linear weight: margin {lin:+.4f} at b = {blin:.4f} (L = {L:.4f}, R = {R:.4f}); "
                    f"optimised g: margin {marg:+.4f} (R = {Ropt:.4f}, support up to t = {supp:.3f}, {its} cuts)")
            out.append(line)
            print(line, flush=True)
            if best is None or marg > best[0]:
                best = (marg, a, b, g, Wt)
        marg, a, b, g, Wt = best
        out.append(f"   BEST for ({k},{kp}): margin {marg:+.4f} at a = {a:.4f}")
        tt = Wt.t[:Wt.nvar]
        samp = [(float(tt[i]), float(g[i])) for i in range(0, Wt.nvar, max(1, Wt.nvar // 16))]
        out.append("      g(t) at sample points: " + ", ".join(f"g({t:.3f})={v:.3f}" for t, v in samp))
        for kk in (3, 4, 5, 6):
            val, conf = Wt.Gk(g, kk)
            out.append(f"      G_{kk}(1) = {val:.4f} at t = {[round(c, 3) for c in conf]}")
    text = "\n".join(out)
    print(text)
    with open(os.path.join(HERE, '..', 'results', f'optimal_weights_{theta:.3f}.txt'), 'w', encoding='utf-8') as fh:
        fh.write(text + "\n")
